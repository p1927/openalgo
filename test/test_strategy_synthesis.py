def test_synthesize_win_prob_weight_breaks_ties_between_similar_shapes():
    # Compares a bought near-the-money call (win probability tops out
    # around 50% — see test_win_probability_selling_far_otm_call_is_high's
    # docstring for why) against a sold far-OTM call (high win probability,
    # low reward). Weighting win-probability should be reflected in each
    # result's reported figure and rank the higher-probability one first
    # when shape fit is otherwise comparable.
    candidates = [
        LegCandidate(strike=k, option_type="CE", premium=p)
        for k, p in [(70, 31), (90, 12), (95, 8), (100, 5), (150, 0.3)]
    ]
    target_points = [(60.0, -10.0), (100.0, -10.0), (110.0, 5.0), (160.0, 5.0)]

    results = synthesize(
        target_points=target_points,
        candidates=candidates,
        max_legs=1,
        min_legs=1,
        top_n=10,  # covers every single-leg combo (5 strikes x 2 sides) so both compared legs are present
        shape_weight=0.5,
        profit_weight=0.0,
        loss_weight=0.0,
        win_prob_weight=0.5,
        spot=100.0,
        iv=0.25,
        years=20 / 365,
    )

    assert results
    top = results[0]
    assert 0.0 <= top.win_probability <= 1.0
    atm_buy_result = next(r for r in results if r.legs[0].strike == 100 and r.legs[0].side == "BUY")
    otm_sell_result = next(
        r for r in results if r.legs[0].strike == 150 and r.legs[0].side == "SELL"
    )
    assert otm_sell_result.win_probability > atm_buy_result.win_probability


def test_synthesize_high_profit_combo_ranks_above_low_profit_at_similar_shape():
    # User priority: "I don't want legs which give me very less profit.
    # Want more profit." When shape fit is roughly comparable between
    # two candidates, the one with materially higher absolute max profit
    # must win — even if the smaller-profit one is a "safer" structure.
    # Here a long 95-strike call (high absolute profit, same shape fit
    # as the rising part of a 90/100 spread) outranks the 90/100 spread
    # whose capped max profit is tiny in absolute terms.
    candidates = [
        LegCandidate(strike=k, option_type="CE", premium=p)
        for k, p in [(90, 12), (95, 9), (100, 6), (105, 4), (110, 2.5), (115, 1.5), (120, 1)]
    ]
    target_points = [(80.0, 0.0), (100.0, 4.0), (140.0, 50.0)]

    results = synthesize(
        target_points=target_points,
        candidates=candidates,
        max_legs=2,
        min_legs=1,
        top_n=5,
        spot=100.0,
        iv=0.25,
        years=15 / 365,
    )

    assert results
    top = results[0]
    # The top result should have a meaningful absolute max profit, not
    # the few-rupee payoff of a tight spread.
    has_real_profit = (
        top.risk.max_profit == float("inf") or top.risk.max_profit >= 5000.0
    )
    assert has_real_profit, (
        f"top result {[(l.side, l.strike) for l in top.legs]} has max_profit="
        f"{top.risk.max_profit} — too small. User said 'I don't want legs "
        f"which give me very less profit'."
    )


def test_synthesize_default_weights_penalize_unlimited_loss_combos():
    # User priority: "low risk" matters. The new formula's loss_score
    # axis correctly penalizes a combo with unlimited max loss (a
    # naked sold call past the highest strike). A naked long call
    # (unlimited max profit, bounded max loss) outranks a naked sold
    # call (limited max profit, unlimited max loss) under the new
    # default weights, even though the sold call has a much higher
    # win probability.
    candidates = [
        LegCandidate(strike=k, option_type="CE", premium=p)
        for k, p in [(90, 12), (95, 9), (100, 6), (105, 4), (110, 2.5), (115, 1.5), (120, 1)]
    ]
    target_points = [(80.0, 0.0), (100.0, 0.0), (120.0, 5.0), (140.0, 20.0)]

    results = synthesize(
        target_points=target_points,
        candidates=candidates,
        max_legs=1,
        min_legs=1,
        top_n=10,
        spot=100.0,
        iv=0.25,
        years=15 / 365,
    )

    assert results
    # Find the naked sold call and the naked long call in the results.
    sold_call = next(
        (r for r in results if r.legs[0].side == "SELL" and r.risk.max_loss == -math.inf),
        None,
    )
    long_call = next(
        (r for r in results if r.legs[0].side == "BUY" and r.risk.max_profit == math.inf),
        None,
    )
    if sold_call and long_call:
        assert long_call.score > sold_call.score, (
            f"naked long call score={long_call.score:.3f} should beat "
            f"naked sold call score={sold_call.score:.3f} — the new "
            f"default weights must penalize unlimited max loss. "
            f"User said 'minimize risk'."
        )


