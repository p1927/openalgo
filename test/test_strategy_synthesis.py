def test_synthesize_ranks_high_profit_high_win_above_perfect_shape_low_profit():
    # User priority for the Draw Target recommendations: high win rate
    # first, then more profit, then less risk, with shape as a *gate*
    # rather than the primary axis. A near-perfect shape match on a
    # tiny-payoff spread must NOT outrank a clearly more profitable,
    # higher-win-probability combo just because the user's drawn target
    # happened to fit a low-payoff body.
    #
    # Concretely: the target is the exact payoff of a 100/115 bull
    # call spread. Under the old shape-dominant ranking, the spread
    # always won because its shape fit was ~perfect (1.0) while any
    # alternative lost on shape. Under the new ranking, a long call
    # at strike 100 has the same ~perfect shape (it's the rising part
    # of the spread) and dramatically better absolute max profit
    # (unlimited) and a comparable win probability, so it ranks first.
    candidates = [
        LegCandidate(strike=k, option_type="CE", premium=p)
        for k, p in [(90, 12), (95, 9), (100, 6), (105, 4), (110, 2.5), (115, 1.5), (120, 1)]
    ]
    prices = np.linspace(80, 140, 121)
    # Draw a flat-top target that the user *might* have intended as a
    # spread, but the ranking should be driven by the holy-grail axes
    # (win, profit, risk), not by the shape alone.
    target_points = [(80.0, 0.0), (100.0, 0.0), (115.0, 4.5), (140.0, 4.5)]

    results = synthesize(
        target_points=target_points,
        candidates=candidates,
        max_legs=2,
        min_legs=1,
        top_n=5,
        spot=100.0,
        iv=0.25,
        years=15 / 365,
    )

    assert results
    # The new priority: high profit + good shape beats a tiny-payoff
    # structure that happens to match the drawn flat-top exactly.
    # We don't pin the *exact* top result (a long call at the right
    # strike is the obvious winner; the precise strike can shift as
    # the synthesis heuristics evolve) — we assert the qualitative
    # property: the top combo has meaningful absolute max profit,
    # not the 4.5-rupee credit-spread payoff the shape alone would
    # suggest.
    top = results[0]
    if top.risk.max_profit == float("inf"):
        max_profit_finite = True
    else:
        max_profit_finite = top.risk.max_profit >= 10.0  # >> 4.5 the shape-only payoff
    assert max_profit_finite, (
        f"top result is {[(l.side, l.strike) for l in top.legs]} with max_profit="
        f"{top.risk.max_profit} — the small-payoff spread is winning on shape alone. "
        f"User explicitly asked for 'more profit, not legs that give very little'."
    )


def test_synthesize_falls_back_to_greedy_for_large_candidate_pools():
    # 40 strikes x 2 types x 2 sides = 160 templates; choosing 4 is
    # ~52M combinations, well above the exhaustive-search cap, so this
    # exercises the greedy + local-search path instead.
    candidates = [
        LegCandidate(strike=float(k), option_type=t, premium=max(0.5, 20 - abs(k - 100) * 0.3))
        for k in range(60, 140, 2)
        for t in ("CE", "PE")
    ]
    target_points = [(60.0, -5.0), (100.0, -5.0), (110.0, 15.0), (140.0, 15.0)]

    results = synthesize(target_points=target_points, candidates=candidates, max_legs=4, top_n=3)

    assert results
    assert all(1 <= len(r.legs) <= 4 for r in results)
    assert all(math.isfinite(r.risk.max_loss) or r.risk.max_loss == -math.inf for r in results)


