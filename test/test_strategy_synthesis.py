def test_combo_payoff_bull_call_spread_shape():
    prices = np.array([80.0, 100.0, 110.0, 120.0, 140.0])
    legs = [
        SynthesizedLeg(strike=100, option_type="CE", side="BUY", premium=5),
        SynthesizedLeg(strike=120, option_type="CE", side="SELL", premium=2),
    ]
    payoff = combo_payoff(prices, legs, LOT_SIZE)

    assert payoff[0] == pytest.approx(-3.0)  # below both strikes: net premium paid, flat
    assert payoff[2] == pytest.approx((110 - 100) - 3.0)  # between strikes: rises 1:1
    assert payoff[3] == pytest.approx(20 - 3.0)  # at/above short strike: capped
    assert payoff[4] == pytest.approx(20 - 3.0)


